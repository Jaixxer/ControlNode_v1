// Package deploy turns a locally stored project directory into something a
// worker can build and run: it validates the project type, copies it to a
// scratch directory without the heavy build artefacts, makes sure a Dockerfile
// exists, and packs the result into a tar.gz for shipping over the wire.
package deploy

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	// DockerfileName is the file a worker builds from.
	DockerfileName = "Dockerfile"
	// ComposeFileName is the file a worker runs when present.
	ComposeFileName = "docker-compose.yml"
	// OverrideFileName is the compose override written when a project ships its
	// own compose file but publishes no ports.
	OverrideFileName = "docker-compose.override.yml"

	// UnsupportedMsg is the user facing error for a project we cannot deploy.
	UnsupportedMsg = "only node apps or js frontend apps are supported: expected a package.json or package-lock.json in the project directory"

	// DefaultContainerPort is the port a generated compose file publishes. It is
	// the node convention; override it with --container-port.
	DefaultContainerPort = 3000
)

// GeneratedDockerfile is written when the project does not ship one.
func GeneratedDockerfile(containerPort int) string {
	return fmt.Sprintf(`# Generated by controlplane: no Dockerfile was found in the project.
FROM node:22-alpine

WORKDIR /app

# Install dependencies first so this layer caches across source changes.
COPY package*.json ./
RUN npm install

COPY . .

EXPOSE %d

CMD ["npm", "start"]
`, containerPort)
}

// skippedDirs are never copied into the staged project: dependencies are
// reinstalled inside the image and VCS history is not needed to build.
var skippedDirs = map[string]bool{
	"node_modules": true,
	".git":         true,
}

// IsNodeProject reports whether dir holds a node/js project, i.e. it contains a
// package.json or package-lock.json.
func IsNodeProject(dir string) (bool, error) {
	info, err := os.Stat(dir)
	if err != nil {
		return false, err
	}
	if !info.IsDir() {
		return false, fmt.Errorf("%s is not a directory", dir)
	}

	for _, name := range []string{"package.json", "package-lock.json"} {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			return true, nil
		}
	}
	return false, nil
}

// Stage copies srcDir into destDir, skipping node_modules and .git. destDir is
// created if needed and is expected to be a fresh directory.
func Stage(srcDir, destDir string) error {
	if err := os.MkdirAll(destDir, 0o755); err != nil {
		return fmt.Errorf("creating staging dir: %w", err)
	}

	return filepath.Walk(srcDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}

		rel, err := filepath.Rel(srcDir, path)
		if err != nil {
			return err
		}
		if rel == "." {
			return nil
		}
		if info.IsDir() && skippedDirs[info.Name()] {
			return filepath.SkipDir
		}

		target := filepath.Join(destDir, rel)

		switch {
		case info.IsDir():
			return os.MkdirAll(target, info.Mode().Perm())
		case info.Mode()&os.ModeSymlink != 0:
			// Symlinks could point anywhere on the worker, so skip them.
			return nil
		case !info.Mode().IsRegular():
			return nil
		default:
			return copyFile(path, target, info.Mode().Perm())
		}
	})
}

func copyFile(src, dst string, mode os.FileMode) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()

	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, mode)
	if err != nil {
		return err
	}
	defer out.Close()

	_, err = io.Copy(out, in)
	return err
}

// BuildFiles describes what EnsureBuildFiles did, so callers can tell the
// operator which files appeared and anything they should know about.
type BuildFiles struct {
	// Created lists files written, relative to the project root.
	Created []string
	// Notes are remarks worth surfacing, such as a flag that could not be
	// applied. These are not errors.
	Notes []string
}

// composeService is one service from a compose file.
type composeService struct {
	Name     string
	HasPorts bool
	HasBuild bool
}

// composeServices lists a compose file's services in the order they are declared.
func composeServices(path string) ([]composeService, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var doc struct {
		Services map[string]struct {
			Ports []any `yaml:"ports"`
			Build any   `yaml:"build"`
		} `yaml:"services"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, err
	}

	// A second pass over the node tree preserves declaration order, which the map
	// above cannot: the port is injected into a single chosen service, so "which
	// one comes first" has to be stable.
	var root yaml.Node
	if err := yaml.Unmarshal(data, &root); err != nil {
		return nil, err
	}
	if len(root.Content) == 0 {
		return nil, nil
	}
	servicesNode := mappingValue(root.Content[0], "services")
	if servicesNode == nil || servicesNode.Kind != yaml.MappingNode {
		return nil, nil
	}

	out := make([]composeService, 0, len(servicesNode.Content)/2)
	for i := 0; i+1 < len(servicesNode.Content); i += 2 {
		name := servicesNode.Content[i].Value
		svc := doc.Services[name]
		out = append(out, composeService{
			Name:     name,
			HasPorts: len(svc.Ports) > 0,
			HasBuild: svc.Build != nil,
		})
	}
	return out, nil
}

// mappingValue returns the value node for a key in a mapping node, or nil.
func mappingValue(node *yaml.Node, key string) *yaml.Node {
	if node == nil || node.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(node.Content); i += 2 {
		if node.Content[i].Value == key {
			return node.Content[i+1]
		}
	}
	return nil
}

// EnsureBuildFiles makes sure a staged project can be built and reached.
//
// It writes a Dockerfile when the project has none, and a compose file too when
// it has neither. When the project brings its own compose but publishes no
// ports, an override file is written next to it: a compose with no ports leaves
// the app unreachable and gives the deploy no URL to report.
//
// Compose only merges an override when it is passed with -f, which the worker
// does, so writing the file alone is not enough.
//
// containerPort is the port the app listens on inside the container. hostPort
// pins the published port; 0 lets Docker allocate a free one, which avoids
// collisions when several workers share a host.
func EnsureBuildFiles(dir, project string, containerPort, hostPort int) (*BuildFiles, error) {
	res := &BuildFiles{}
	if containerPort <= 0 {
		containerPort = DefaultContainerPort
	}

	dockerfile := filepath.Join(dir, DockerfileName)
	if _, err := os.Stat(dockerfile); os.IsNotExist(err) {
		if err := os.WriteFile(dockerfile, []byte(GeneratedDockerfile(containerPort)), 0o644); err != nil {
			return res, fmt.Errorf("writing %s: %w", DockerfileName, err)
		}
		res.Created = append(res.Created, DockerfileName)
	} else if err != nil {
		return res, err
	}

	// A bare "3000" publishes that container port on an arbitrary host port,
	// which is what makes concurrent deploys on one host safe. The actual port is
	// read back from docker afterwards.
	published := fmt.Sprintf("%d", containerPort)
	if hostPort > 0 {
		published = fmt.Sprintf("%d:%d", hostPort, containerPort)
	}

	compose := filepath.Join(dir, ComposeFileName)
	if _, err := os.Stat(compose); os.IsNotExist(err) {
		body := fmt.Sprintf(`services:
  app:
    build: .
    image: %s:latest
    ports:
      - "%s"
    restart: unless-stopped
`, project, published)
		if err := os.WriteFile(compose, []byte(body), 0o644); err != nil {
			return res, fmt.Errorf("writing %s: %w", ComposeFileName, err)
		}
		res.Created = append(res.Created, ComposeFileName)
		return res, nil
	} else if err != nil {
		return res, err
	}

	// The project ships its own compose.
	override := filepath.Join(dir, OverrideFileName)
	if _, err := os.Stat(override); err == nil {
		// Already prepared, e.g. generated by the control plane and shipped here.
		return res, nil
	}

	services, err := composeServices(compose)
	if err != nil {
		res.Notes = append(res.Notes, fmt.Sprintf("could not read %s to check its ports: %v", ComposeFileName, err))
		return res, nil
	}
	if len(services) == 0 {
		res.Notes = append(res.Notes, fmt.Sprintf("%s declares no services, so no port was published", ComposeFileName))
		return res, nil
	}
	for _, svc := range services {
		if svc.HasPorts {
			res.Notes = append(res.Notes, fmt.Sprintf("%s publishes its own ports, so --port and --container-port were not applied to it", ComposeFileName))
			return res, nil
		}
	}

	// Prefer a service that builds (the app this pipeline deploys) over a
	// supporting one such as a database, which may not be a web server at all.
	target := services[0].Name
	for _, svc := range services {
		if svc.HasBuild {
			target = svc.Name
			break
		}
	}

	body := fmt.Sprintf(`# Generated by controlplane: %s publishes no ports, so the app would be
# unreachable. This override adds one. Compose only merges it when passed
# with -f, which the worker does.
services:
  %s:
    ports:
      - "%s"
`, ComposeFileName, target, published)
	if err := os.WriteFile(override, []byte(body), 0o644); err != nil {
		return res, fmt.Errorf("writing %s: %w", OverrideFileName, err)
	}
	res.Created = append(res.Created, OverrideFileName)

	if len(services) > 1 {
		res.Notes = append(res.Notes, fmt.Sprintf("%s has %d services; the port was published on %q. Add ports to %s yourself if that is the wrong one",
			ComposeFileName, len(services), target, ComposeFileName))
	}
	return res, nil
}

// Archive packs dir into an in-memory tar.gz, which is what gets shipped to a
// worker. node_modules and .git are skipped, matching Stage.
func Archive(dir string) ([]byte, error) {
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)

	walkErr := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}

		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		if rel == "." {
			return nil
		}
		if info.IsDir() && skippedDirs[info.Name()] {
			return filepath.SkipDir
		}
		if !info.Mode().IsRegular() && !info.IsDir() {
			return nil
		}

		hdr, err := tar.FileInfoHeader(info, "")
		if err != nil {
			return err
		}
		hdr.Name = filepath.ToSlash(rel)
		if info.IsDir() {
			hdr.Name += "/"
		}
		if err := tw.WriteHeader(hdr); err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			return nil
		}

		f, err := os.Open(path)
		if err != nil {
			return err
		}
		defer f.Close()

		_, err = io.Copy(tw, f)
		return err
	})

	if walkErr != nil {
		return nil, walkErr
	}
	if err := tw.Close(); err != nil {
		return nil, err
	}
	if err := gz.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// ProjectName derives a container/image safe name from a directory path.
func ProjectName(dir string) string {
	return SanitizeName(filepath.Base(filepath.Clean(dir)))
}

// SanitizeName reduces an arbitrary string to something safe to use as a docker
// image, compose project and directory name: lowercase letters, digits, dash
// and underscore only.
func SanitizeName(name string) string {
	name = strings.ToLower(name)
	var b strings.Builder
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-', r == '_':
			b.WriteRune(r)
		default:
			b.WriteRune('-')
		}
	}
	out := strings.Trim(b.String(), "-")
	if out == "" {
		return "project"
	}
	return out
}

// ResolveProjectRoot returns the directory that actually holds the project.
//
// GitHub's tarball endpoint wraps everything in a single "owner-repo-sha"
// directory, while an archive produced by Archive has the project at the top
// level. Descending through single-child directories handles both without the
// caller having to know which source it came from.
func ResolveProjectRoot(dir string) (string, error) {
	current := dir
	for depth := 0; depth < 4; depth++ {
		if ok, _ := IsNodeProject(current); ok {
			return current, nil
		}

		entries, err := os.ReadDir(current)
		if err != nil {
			return "", err
		}
		var subdirs []string
		for _, e := range entries {
			if e.IsDir() && !skippedDirs[e.Name()] {
				subdirs = append(subdirs, e.Name())
			}
		}
		if len(subdirs) != 1 {
			return "", fmt.Errorf("%s", UnsupportedMsg)
		}
		current = filepath.Join(current, subdirs[0])
	}
	return "", fmt.Errorf("could not find the project root under %s: %s", dir, UnsupportedMsg)
}

// Unpack extracts a tar.gz produced by Archive into destDir. Entries that would
// escape destDir are rejected.
func Unpack(archive []byte, destDir string) error {
	return UnpackTarGz(bytes.NewReader(archive), destDir, false)
}

// UnpackTarGz streams a tar.gz into destDir. Nothing is buffered in memory, so
// this works for archives piped straight off the network.
//
// stripTopDir drops the first path component of every entry. GitHub's tarball
// endpoint wraps the whole repo in a single "owner-repo-sha/" directory, and
// that wrapper would otherwise end up as a stray directory in the project.
//
// Entries that would escape destDir are rejected.
func UnpackTarGz(r io.Reader, destDir string, stripTopDir bool) error {
	gz, err := gzip.NewReader(r)
	if err != nil {
		return fmt.Errorf("reading archive: %w", err)
	}
	defer gz.Close()

	if err := os.MkdirAll(destDir, 0o755); err != nil {
		return err
	}
	root := filepath.Clean(destDir)

	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return fmt.Errorf("reading archive entry: %w", err)
		}

		name := hdr.Name
		if stripTopDir {
			if i := strings.IndexByte(name, '/'); i >= 0 {
				name = name[i+1:]
			} else {
				// The top level directory entry itself.
				continue
			}
			if name == "" {
				continue
			}
		}

		target := filepath.Join(root, filepath.FromSlash(name))
		if target != root && !strings.HasPrefix(target, root+string(os.PathSeparator)) {
			return fmt.Errorf("archive entry %q escapes the target directory", hdr.Name)
		}

		switch hdr.Typeflag {
		case tar.TypeDir:
			if err := os.MkdirAll(target, 0o755); err != nil {
				return err
			}
		case tar.TypeReg:
			if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
				return err
			}
			f, err := os.OpenFile(target, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o644)
			if err != nil {
				return err
			}
			if _, err := io.Copy(f, tr); err != nil {
				f.Close()
				return err
			}
			if err := f.Close(); err != nil {
				return err
			}
		}
	}
}
